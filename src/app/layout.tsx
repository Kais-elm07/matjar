import type { Metadata, Viewport } from "next"
import localFont from "next/font/local"

import { Analytics } from "@/components/store/analytics"
import { LazyToaster } from "@/components/store/lazy-toaster"
import { DirectionProvider } from "@/components/ui/direction"
import { siteConfig } from "@/config/site"
import { openGraph } from "@/lib/seo"

import "./globals.css"

// IBM Plex Sans Arabic is hosted inside the project (OFL license in src/fonts/ibm-plex-sans-arabic),
// so the site build does not stop if Google Fonts cannot be reached.
// The files are subset copies with only the characters the store needs, generated by the pnpm fonts command from assets/fonts.
// The font has static weights, and three are used: 400, 500 and 700.
// The first set is for Arabic letters, and the second for digits and Latin letters;
// their order in the font stack is set by --font-sans in src/app/globals.css
const plexArabic = localFont({
  src: [
    {
      path: "../fonts/ibm-plex-sans-arabic/ibm-plex-sans-arabic-arabic-400-normal.woff2",
      weight: "400",
    },
    {
      path: "../fonts/ibm-plex-sans-arabic/ibm-plex-sans-arabic-arabic-500-normal.woff2",
      weight: "500",
    },
    {
      path: "../fonts/ibm-plex-sans-arabic/ibm-plex-sans-arabic-arabic-700-normal.woff2",
      weight: "700",
    },
  ],
  display: "swap",
  variable: "--font-arabic",
  // The automatic fallback font also covers Latin letters, which would keep the digit files from being used
  adjustFontFallback: false,
})

const plexLatin = localFont({
  src: [
    {
      path: "../fonts/ibm-plex-sans-arabic/ibm-plex-sans-arabic-latin-400-normal.woff2",
      weight: "400",
    },
    {
      path: "../fonts/ibm-plex-sans-arabic/ibm-plex-sans-arabic-latin-500-normal.woff2",
      weight: "500",
    },
    {
      path: "../fonts/ibm-plex-sans-arabic/ibm-plex-sans-arabic-latin-700-normal.woff2",
      weight: "700",
    },
  ],
  display: "swap",
  variable: "--font-latin",
  // Not preloaded, so it does not compete with the Arabic letters and the images for the connection at the start of the page;
  // the browser requests it at the first digit or English letter, and digits show in the fallback font until it arrives
  preload: false,
})

export const metadata: Metadata = {
  metadataBase: new URL(siteConfig.url),
  title: {
    default: `${siteConfig.name} | ${siteConfig.tagline}`,
    template: `%s | ${siteConfig.name}`,
  },
  description: siteConfig.description,
  openGraph: openGraph({
    title: siteConfig.name,
    description: siteConfig.description,
  }),
  // X (Twitter) takes the title and image from openGraph, and shows the image at full width
  twitter: { card: "summary_large_image" },
}

export const viewport: Viewport = {
  // The mobile browser bar takes the store's dark background color, and native fields and menus are dark too
  themeColor: "#121214",
  colorScheme: "dark",
}

export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="ar"
      dir="rtl"
      className={`${plexArabic.variable} ${plexLatin.variable} h-full antialiased`}
    >
      <body className="flex min-h-full flex-col">
        <DirectionProvider direction="rtl">
          {children}
          <LazyToaster />
          <Analytics />
        </DirectionProvider>
      </body>
    </html>
  )
}
